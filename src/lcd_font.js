function parse(src, h, gap) {
  const out = {};
  for (const [ch, s] of Object.entries(src)) {
    const rows = s.split('|'); const w = rows[0].length; const bits = new Uint8Array(w * h);
    rows.forEach((r, y) => { for (let x = 0; x < w; x++) if (r[x] === '#') bits[y * w + x] = 1; });
    out[ch] = { w, h, a: w + gap, bits };
  }
  return out;
}
// Scale2x / EPX (bordas diagonais suavizadas ao ampliar 2×)
function scale2x(g) {
  const { w, h, bits } = g, W = w * 2, H = h * 2, o = new Uint8Array(W * H);
  const at = (x, y) => (x < 0 || y < 0 || x >= w || y >= h ? 0 : bits[y * w + x]);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const P = at(x, y), A = at(x, y - 1), B = at(x + 1, y), C = at(x - 1, y), D = at(x, y + 1);
    let e1 = P, e2 = P, e3 = P, e4 = P;
    if (C === A && C !== D && A !== B) e1 = A;
    if (A === B && A !== C && B !== D) e2 = B;
    if (D === C && D !== B && C !== A) e3 = C;
    if (B === D && B !== A && D !== C) e4 = D;
    o[(2 * y) * W + 2 * x] = e1; o[(2 * y) * W + 2 * x + 1] = e2; o[(2 * y + 1) * W + 2 * x] = e3; o[(2 * y + 1) * W + 2 * x + 1] = e4;
  }
  return { w: W, h: H, bits: o };
}
// média: Scale2x da S (10 colunas) → remove as sub-colunas 3 e 7 (colunas internas da S ficam com 1 px, hastes com 2 px)
function toMedium(g, bold) {
  const e = scale2x({ w: 5, h: 9, bits: padRows(g, 9) }); const keep = [0, 1, 2, 4, 5, 6, 8, 9];
  const w = keep.length + (bold ? 1 : 0), h = e.h, bits = new Uint8Array(w * h);
  const src = (y, x) => (x >= 0 && x < keep.length ? e.bits[y * e.w + keep[x]] : 0);
  for (let y = 0; y < h; y++) for (let x = 0; x < keep.length; x++) if (src(y, x)) {
    bits[y * w + x] = 1;
    if (bold && (src(y, x + 1) || !src(y, x + 2))) bits[y * w + x + 1] = 1; // engrossa sem fechar vãos de 1 px (m, w, M…)
  }
  return { w, h, a: w + 1, bits };
}
function padRows(g, h) { const b = new Uint8Array(g.w * h); b.set(g.bits.subarray(0, Math.min(g.bits.length, b.length))); return b; }

